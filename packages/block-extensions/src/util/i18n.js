// Older versions stored WordPress locales (e.g. `nl_NL`, `bel`) instead of BCP 47 tags.
const LEGACY_CODES = {
	arg: 'an',
	bel: 'be',
	dzo: 'dz',
	kir: 'ky',
	oci: 'oc',
	snd: 'sd',
	tah: 'ty',
};

export function toLanguageTag( code ) {
	const base = code.replace( /_(formal|informal|ao90)$/, '' );

	return LEGACY_CODES[ base ] || base.replace( /_/g, '-' );
}
